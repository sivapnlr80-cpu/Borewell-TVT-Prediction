            "def load_dicom_as_array(path: str, img_size: int = CFG['img_size']):\n",
            "    try:\n",
            "        dcm = pydicom.dcmread(path)\n",
            "        img = dcm.pixel_array.astype(np.float32)\n",
            "        slope = float(getattr(dcm, 'RescaleSlope', 1.0) or 1.0)\n",
            "        intercept = float(getattr(dcm, 'RescaleIntercept', 0.0) or 0.0)\n",
            "        img = img * slope + intercept\n",
            "        if getattr(dcm, 'PhotometricInterpretation', '') == 'MONOCHROME1':\n",
            "            img = np.max(img) - img\n",
            "        mn, mx = img.min(), img.max()\n",
            "        img = ((img - mn) / (mx - mn) * 255.0).astype(np.uint8) if mx > mn else np.zeros_like(img, dtype=np.uint8)\n",
            "        if img.ndim == 2:\n",
            "            img = np.stack([img, img, img], axis=-1)\n",
            "        elif img.shape[-1] != 3:\n",
            "            img = img[..., :3]\n",
            "        return cv2.resize(img, (img_size, img_size))\n",
            "    except Exception:\n",
            "        return None"
